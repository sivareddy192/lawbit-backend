import mongoose from 'mongoose';

const restaurantApplicationSchema = new mongoose.Schema({
  applicationId: { type: String, unique: true, sparse: true, index: true },
  restaurant: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Restaurant',
    required: true,
    unique: true,
    index: true,
  },
  applicant: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
    index: true,
  },
  status: {
    type: String,
    enum: ['PENDING', 'UNDER_REVIEW', 'ADDITIONAL_DOCUMENTS_REQUIRED', 'APPROVED', 'REJECTED', 'SUSPENDED'],
    default: 'PENDING',
    index: true,
  },
  applicationStatus: { type: String, enum: ['PENDING','UNDER_REVIEW','ADDITIONAL_DOCUMENTS_REQUIRED','APPROVED','REJECTED','SUSPENDED'] },
  restaurantName: { type: String, default: '' },
  restaurantLogo: { type: String, default: '' },
  restaurantCoverImage: { type: String, default: '' },
  restaurantDescription: { type: String, default: '' },
  cuisineCategory: { type: mongoose.Schema.Types.Mixed, default: [] },
  restaurantEmail: { type: String, default: '' },
  restaurantPhone: { type: String, default: '' },
  alternatePhone: { type: String, default: '' },
  restaurantAddress: { type: String, default: '' },
  city: { type: String, default: '' },
  state: { type: String, default: '' },
  pinCode: { type: String, default: '' },
  location: {
    latitude: { type: Number, default: null },
    longitude: { type: Number, default: null },
    googleMapsUrl: { type: String, default: '' },
  },
  openingTime: { type: String, default: '' },
  closingTime: { type: String, default: '' },
  operatingDays: [{ type: String }],
  ownerDetails: {
    fullName: { type: String, default: '' },
    profilePhoto: { type: String, default: '' },
    email: { type: String, default: '' },
    phone: { type: String, default: '' },
    alternatePhone: { type: String, default: '' },
    residentialAddress: { type: String, default: '' },
  },
  businessDocuments: {
    fssaiNumber: { type: String, default: '' },
    fssaiDocument: { type: String, default: '' },
    gstNumber: { type: String, default: '' },
    gstCertificate: { type: String, default: '' },
    panNumber: { type: String, default: '' },
    panDocument: { type: String, default: '' },
    identityProof: { type: String, default: '' },
    businessRegistrationCertificate: { type: String, default: '' },
  },
  bankDetails: {
    accountHolderName: { type: String, default: '' },
    accountNumber: { type: String, default: '' },
    ifscCode: { type: String, default: '' },
    bankName: { type: String, default: '' },
    bankProof: { type: String, default: '' },
  },
  additionalInformation: {
    averagePreparationTime: { type: String, default: '' },
    specialties: { type: mongoose.Schema.Types.Mixed, default: [] },
    deliveryOptions: { type: mongoose.Schema.Types.Mixed, default: [] },
    termsAccepted: { type: Boolean, default: false },
  },
  reviewNotes: { type: String, default: '' },
  rejectionReason: { type: String, default: '' },
  adminNotes: { type: String, default: '' },
  submittedAt: { type: Date, default: null },
  reviewedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  reviewedAt: { type: Date, default: null },
  approvedAt: { type: Date, default: null },
  rejectedAt: { type: Date, default: null },
}, { timestamps: true });

export default mongoose.models.RestaurantApplication
  || mongoose.model('RestaurantApplication', restaurantApplicationSchema);
